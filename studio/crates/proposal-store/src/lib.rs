//! Bounded, immutable, untrusted proposal data. This crate never saves a manuscript,
//! grants access, approves a patch, or treats client labels/hashes as authentication.
use repository_core::{Repository, MAX_FILE_BYTES};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::{fmt, path::Path};

#[cfg(unix)]
mod storage;
#[cfg(unix)]
pub use storage::ProposalStore;

pub const MAX_PROPOSALS: usize = 256;
pub const MAX_STORE_BYTES: u64 = 64 * 1024 * 1024;
pub const MAX_RECORD_BYTES: u64 = MAX_FILE_BYTES * 12 + 64 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Error {
    InvalidProposal,
    InvalidStorage,
    StorageIo,
    StorageUncertain,
    LimitExceeded,
    Conflict,
    NotFound,
    Source(repository_core::Error),
}
impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::InvalidProposal => "Proposal is invalid or unsupported",
            Self::InvalidStorage => {
                "Proposal storage must be private, safe, and outside the repository"
            }
            Self::StorageIo => "Proposal storage is unavailable",
            Self::StorageUncertain => {
                "Proposal may be stored but durability is uncertain; inspect before retrying"
            }
            Self::LimitExceeded => "Proposal storage limit reached",
            Self::Conflict => "Scene changed since the snapshot; read it again before proposing",
            Self::NotFound => "Proposal was not found in the selected project",
            Self::Source(_) => "Selected source is unavailable or not permitted",
        })
    }
}
impl std::error::Error for Error {}
impl From<repository_core::Error> for Error {
    fn from(error: repository_core::Error) -> Self {
        Self::Source(error)
    }
}
pub type Result<T> = std::result::Result<T, Error>;

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ProposalOrigin {
    pub kind: String,
    pub session_id: String,
    pub client_label: String,
    pub identity_assurance: String,
}
impl ProposalOrigin {
    /// The session ID is generated by the server. A client label is unverified text.
    /// Neither value is an authenticated author identity or a capability.
    pub fn local_mcp(session_id: String, client_label: String) -> Self {
        Self {
            kind: "localMcp".into(),
            session_id,
            client_label,
            identity_assurance: "unverifiedLocalProcess".into(),
        }
    }
    fn validate(&self) -> Result<()> {
        if self.kind != "localMcp"
            || !valid_id(&self.session_id)
            || self.identity_assurance != "unverifiedLocalProcess"
            || self.client_label.is_empty()
            || self.client_label.len() > 128
            || self.client_label.chars().any(char::is_control)
        {
            return Err(Error::InvalidProposal);
        }
        Ok(())
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PendingProposal {
    pub schema_version: u32,
    pub id: String,
    pub project_key: String,
    pub path: String,
    pub base_hash: String,
    pub replacement_hash: String,
    pub diff_hash: String,
    pub base_text: String,
    pub replacement_text: String,
    pub origin: ProposalOrigin,
    /// Informational Unix milliseconds, never a revision or authorization token.
    pub created_at_ms: u64,
}
impl PendingProposal {
    /// Validates data integrity only. The record remains untrusted even on success.
    pub fn validate(&self) -> Result<()> {
        if self.schema_version != 1
            || !valid_id(&self.id)
            || !valid_hash(&self.project_key)
            || !valid_scene_path(&self.path)
            || self.created_at_ms == 0
            || !valid_text(&self.base_text)
            || !valid_text(&self.replacement_text)
            || self.base_text == self.replacement_text
            || self.base_hash != text_hash(&self.base_text)
            || self.replacement_hash != text_hash(&self.replacement_text)
            || self.diff_hash != diff_hash(&self.path, &self.base_text, &self.replacement_text)
        {
            return Err(Error::InvalidProposal);
        }
        self.origin.validate()
    }
    pub fn summary(&self) -> ProposalSummary {
        ProposalSummary {
            schema_version: self.schema_version,
            id: self.id.clone(),
            project_key: self.project_key.clone(),
            path: self.path.clone(),
            base_hash: self.base_hash.clone(),
            replacement_hash: self.replacement_hash.clone(),
            diff_hash: self.diff_hash.clone(),
            origin: self.origin.clone(),
            created_at_ms: self.created_at_ms,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ProposalSummary {
    pub schema_version: u32,
    pub id: String,
    pub project_key: String,
    pub path: String,
    pub base_hash: String,
    pub replacement_hash: String,
    pub diff_hash: String,
    pub origin: ProposalOrigin,
    pub created_at_ms: u64,
}

pub fn text_hash(text: &str) -> String {
    format!("{:x}", Sha256::digest(text.as_bytes()))
}
/// SHA-256 of the UTF-8 JSON string array below. Array order is fixed; no whitespace.
/// This is an exact whole-scene replacement comparison, not a semantic/line diff.
pub fn diff_hash(path: &str, base: &str, replacement: &str) -> String {
    text_hash(
        &serde_json::to_string(&["heinlein-replace-scene-v1", path, base, replacement])
            .expect("serializing a string array cannot fail"),
    )
}
fn valid_hash(value: &str) -> bool {
    value.len() == 64
        && value
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}
fn valid_id(value: &str) -> bool {
    uuid::Uuid::parse_str(value)
        .is_ok_and(|id| id.to_string() == value && id.get_version_num() == 4)
}
fn valid_text(value: &str) -> bool {
    value.len() as u64 <= MAX_FILE_BYTES
        && !value
            .bytes()
            .any(|b| b == 0 || (b < 32 && !matches!(b, 9 | 10 | 13)))
}
fn valid_scene_path(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 4096
        && !value.contains(['\\', ':'])
        && value.split('/').count() <= 32
        && value.split('/').all(|part| {
            !part.is_empty()
                && part != "."
                && part != ".."
                && !part.starts_with('.')
                && !part.chars().any(char::is_control)
        })
        && matches!(
            Path::new(value)
                .extension()
                .and_then(|s| s.to_str())
                .map(str::to_ascii_lowercase)
                .as_deref(),
            Some("md" | "markdown")
        )
}
fn validate_source(repo: &Repository, path: &str) -> Result<repository_core::Document> {
    if !valid_scene_path(path) {
        return Err(Error::InvalidProposal);
    }
    let document = repo.read(path)?;
    if document.generated_compatibility {
        return Err(Error::InvalidProposal);
    }
    Ok(document)
}
