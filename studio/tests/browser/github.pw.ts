import { test, expect, type Locator } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('GitHub synthetic account, exact-file version, send, draft feedback and explicit conflict journey with keyboard only', async ({ page }) => {
    async function tabTo(target:Locator){await expect(target).toBeVisible();await expect(target).toBeEnabled();for(let i=0;i<100;i++){if(await target.evaluate(el=>el===document.activeElement))return;await page.keyboard.press('Tab');}throw new Error('Keyboard could not reach target: '+await target.textContent());}
    async function activate(target:Locator){await tabTo(target);await page.keyboard.press('Enter');}
    async function type(target:Locator,text:string){await tabTo(target);await page.keyboard.press('ControlOrMeta+A');await page.keyboard.insertText(text);}
    await page.goto('/tests/browser/github.html');
    await activate(page.getByRole('button', { name: 'GitHub projects…', exact: true }));
    const dialog = page.getByRole('dialog', { name: 'GitHub projects', exact: true });
    await expect(dialog).toBeVisible();
    await activate(dialog.getByRole('button', { name: 'Connect GitHub…', exact: true }));
    await expect(dialog).toContainText('SYNTHETIC');
    await activate(dialog.getByRole('button', { name: 'Check sign-in', exact: true }));
    await activate(dialog.getByRole('button', { name: 'Use this GitHub account…', exact: true }));
    await type(dialog.getByLabel('GitHub repository URL', { exact: true }),'https://github.com/example/synthetic-story');
    await activate(dialog.getByRole('button', { name: 'Preview repository…', exact: true }));
    await expect(dialog).toContainText('Private');
    await activate(dialog.getByRole('button', { name: 'Open separate local copy…', exact: true }));
    await expect(dialog).not.toBeVisible();
    await activate(page.getByRole('button', { name: 'GitHub projects…', exact: true }));
    await activate(dialog.getByRole('button', { name: 'Save a version on this computer…', exact: true }));
    await tabTo(dialog.getByRole('checkbox', { name: 'edit: story.md', exact: true })); await page.keyboard.press('Space');
    await type(dialog.getByLabel('Version author name', { exact: true }),'Synthetic Writer');
    await type(dialog.getByLabel('Version author email', { exact: true }),'synthetic@users.noreply.github.com');
    await type(dialog.getByLabel('Version message', { exact: true }),'Synthetic intentional version');
    await activate(dialog.getByRole('button', { name: 'Preview local version', exact: true }));
    await expect(dialog.getByRole('region', { name: 'GitHub action preview' })).toContainText('story.md');
    await activate(dialog.getByRole('button', { name: 'Confirm local version…', exact: true }));
    await expect(dialog).toContainText('Synthetic local version saved. Nothing sent.');
    await activate(dialog.getByRole('button', { name: 'Send local versions to GitHub…', exact: true }));
    await activate(dialog.getByRole('button', { name: 'Preview GitHub action', exact: true }));
    await expect(dialog).toContainText('repository-configured automation');
    await activate(dialog.getByRole('button', { name: 'Confirm sending versions…', exact: true }));
    await activate(dialog.getByRole('button', { name: 'Request feedback with a draft pull request…', exact: true }));
    await type(dialog.getByLabel('Feedback request title', { exact: true }),'Synthetic feedback');
    await type(dialog.getByLabel('Feedback request description', { exact: true }),'Please review this synthetic scene.');
    await activate(dialog.getByRole('button', { name: 'Preview GitHub action', exact: true }));
    await activate(dialog.getByRole('button', { name: 'Confirm draft feedback request…', exact: true }));
    await expect(dialog).toContainText('(draft)');
    await activate(dialog.getByRole('button', { name: 'Review changes on the feedback branch…', exact: true }));
    await expect(dialog).toContainText('No choice is selected');
    await expect(dialog.getByRole('button', { name: 'Apply this reviewed batch…', exact: true })).toHaveCount(0);
    await activate(dialog.getByText('Your writing', { exact: true }));
    await expect(dialog).toContainText('exact author words');
    await activate(dialog.getByRole('button', { name: 'Keep mine', exact: true }));
    await activate(dialog.getByRole('button', { name: 'Apply this reviewed batch…', exact: true }));
    await expect(dialog).toContainText('Synthetic local version saved');
    expect(await page.evaluate(() => ((window as any).githubFixture.calls as {
        action: string;
    }[]).filter(c => c.action === 'confirm').length)).toBe(4);
    const axe = await new AxeBuilder({ page }).include('.github-panel').analyze();
    expect(axe.violations).toEqual([]);
    await activate(dialog.getByRole('button', { name: 'Close GitHub projects', exact: true }));
    await expect(page.getByRole('button', { name: 'GitHub projects…', exact: true })).toBeFocused();
});
test('GitHub panel keyboard entry, Escape focus and high contrast reflow at 200 percent', async ({ page }) => {
    await page.goto('/tests/browser/github.html');
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+=' : 'Control+=');
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+=' : 'Control+=');
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+=' : 'Control+=');
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+=' : 'Control+=');
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+=' : 'Control+=');
    await expect(page.locator('html')).toHaveAttribute('data-zoom', '200');
    const entry = page.getByRole('button', { name: 'GitHub projects…', exact: true });
    await entry.click();
    const dialog = page.getByRole('dialog', { name: 'GitHub projects', exact: true });
    await expect(dialog).toBeVisible();
    await expect(dialog.getByRole('heading', { name: 'GitHub projects', level: 2 })).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(dialog.getByRole('button', { name: 'Close GitHub projects', exact: true })).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(entry).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(dialog).toBeVisible();
    const bounds = await dialog.evaluate(el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right, width: window.innerWidth, scroll: el.scrollWidth, client: el.clientWidth }; });
    expect(bounds.left).toBeGreaterThanOrEqual(0);
    expect(bounds.right).toBeLessThanOrEqual(bounds.width);
    expect(bounds.scroll).toBeLessThanOrEqual(bounds.client + 1);
    const title = await dialog.getByRole('heading', { level: 3, name: 'GitHub projects', exact: true }).boundingBox();
    expect(title!.y).toBeLessThan(420);
    const axe = await new AxeBuilder({ page }).include('.github-panel').analyze();
    expect(axe.violations).toEqual([]);
});
