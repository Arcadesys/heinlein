import {test, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('@smoke entire chapter returns targeted edits without moving or reflowing the current scene', async ({page}, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if (message.type() === 'error') errors.push(message.text());});
  await page.goto('/tests/browser/markdown-reading.html?doc=harbor.md&chapterReview');
  await expect(page).toHaveTitle('Synthetic Markdown reading preview');
  await expect(page).toHaveURL(/chapterReview/);
  await expect(page.locator('.active-document-pane .cm-content')).toContainText('rang twice');
  await page.evaluate(async () => {await document.fonts.ready; (window as any).readingFixture.theme();});
  const shape = () => page.locator('.active-document-pane .cm-content').evaluate(node => ({width: node.getBoundingClientRect().width, text: node.textContent, lines: [...node.children].map(n => ({width: n.getBoundingClientRect().width, height: n.getBoundingClientRect().height}))}));
  const before = await shape();
  const original = await page.evaluate(() => JSON.stringify((window as any).readingFixture.docs));
  await page.getByRole('button', {name: 'Heinlein', exact: true}).click();
  await page.getByRole('button', {name: 'Whole scene', exact: true}).click();
  const panel = page.getByRole('region', {name: 'Heinlein Review', exact: true});
  const chapter = panel.getByRole('button', {name: /Entire chapter…/});
  await chapter.focus(); await chapter.scrollIntoViewIfNeeded();
  expect((await chapter.boundingBox())!.height).toBeGreaterThanOrEqual(48);
  expect((await new AxeBuilder({page}).include('.heinlein-review-panel').analyze()).violations).toEqual([]);
  await page.screenshot({path: `/tmp/heinlein-chapter-entry-${info.project.name}.png`});
  await page.keyboard.press('Enter');
  await expect(panel).toContainText('Entire chapter captured.');
  await expect(panel.getByRole('button', {name: 'Whole chapter', exact: true})).toHaveAttribute('aria-pressed', 'true');
  await expect(panel).toContainText('This chapter');
  await expect(panel.locator('.review-target input:checked')).toHaveCount(2);
  await page.screenshot({path: `/tmp/heinlein-chapter-captured-${info.project.name}.png`});
  expect(await shape()).toEqual(before);
  expect(await page.evaluate(() => (window as any).chapterReviewFixture.requests)).toEqual([]);
  await panel.getByRole('button', {name: 'Preview review', exact: true}).click();
  await expect(panel.getByRole('button', {name: 'Run review', exact: true})).toBeEnabled();
  expect(await page.evaluate(() => (window as any).chapterReviewFixture.previews[0].snapshots.map((s: any) => s.path))).toEqual(['opening.md', 'harbor.md']);
  expect(await page.evaluate(() => (window as any).chapterReviewFixture.requests)).toEqual([]);
  await panel.getByRole('button', {name: 'Run review', exact: true}).click();
  await expect(page.locator('.review-background').getByRole('button', {name: /Open review/})).toBeVisible();
  await page.locator('.review-background').getByRole('button', {name: /Open review/}).click();
  await expect(panel).toBeVisible();
  await expect(panel.locator('.review-edit')).toHaveCount(2);
  await expect(panel).toContainText('were'); await expect(panel).toContainText('was');
  await expect(panel).toContainText('twice'); await expect(panel).toContainText('two times');
  expect(await page.evaluate(() => (window as any).chapterReviewFixture.requests[0].scope)).toBe('chapter');
  expect(await page.evaluate(() => JSON.stringify((window as any).readingFixture.docs))).toBe(original);
  expect(await shape()).toEqual(before);
  expect((await new AxeBuilder({page}).include('.heinlein-review-panel').analyze()).violations).toEqual([]);
  expect(await panel.evaluate(n => n.scrollWidth <= n.clientWidth)).toBe(true);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  await page.screenshot({path: `/tmp/heinlein-chapter-review-${info.project.name}.png`});
  await panel.getByRole('button', {name: 'Close Heinlein', exact: true}).click();
  expect(await shape()).toEqual(before); expect(errors).toEqual([]);
});
