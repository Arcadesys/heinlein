import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('UUID sheet files have readable tabs, keyboard names and full paths in Details',async({page},info)=>{
 const errors:string[]=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 await page.goto('/tests/browser/document-tabs.html?titled');
 await page.waitForFunction(()=>document.documentElement.dataset.tabsReady==='true');
 expect(new URL(page.url()).pathname).toBe('/tests/browser/document-tabs.html');
 await expect(page).toHaveTitle('Synthetic document workspace');
 await page.evaluate(async()=>{document.documentElement.dataset.zoom='200';(window as any).documentFixture.theme(true);await document.fonts.ready;});
 const initial=await page.evaluate(()=>JSON.stringify((window as any).documentFixture.fixture.documents));
 const tabs=page.getByRole('tablist',{name:'Open documents',exact:true});
 const first=tabs.getByRole('tab',{name:'Harvest Moon',exact:true});
 const second=tabs.getByRole('tab',{name:'The morning after',exact:true});
 await expect(first).toHaveText('Harvest Moon');
 await expect(second).toHaveText('The morning after');
 await expect(tabs).not.toContainText('sheet-');
 await first.focus();await page.keyboard.press('Home');await expect(second).toBeFocused();
 await expect(first).toHaveAttribute('aria-selected','true');
 await page.keyboard.press('Enter');await expect(second).toHaveAttribute('aria-selected','true');
 await second.focus();await page.keyboard.press('End');await expect(first).toBeFocused();
 await page.keyboard.press('Enter');await expect(first).toHaveAttribute('aria-selected','true');
 await first.focus();const focus=await first.evaluate(node=>{const style=getComputedStyle(node);return {outline:style.outlineStyle,shadow:style.boxShadow,height:node.getBoundingClientRect().height};});
 expect(focus.outline!=='none'||focus.shadow!=='none').toBe(true);expect(focus.height).toBeGreaterThanOrEqual(48);
 const details=page.getByRole('button',{name:'Document details',exact:true});
 if(!await details.isVisible())await page.getByRole('button',{name:'Documents',exact:true}).click();
 await details.click();
 const dialog=page.getByRole('dialog',{name:'Document details',exact:true});
 const summary=dialog.locator('summary').filter({hasText:'Harvest Moon'});await summary.focus();await page.keyboard.press('Enter');
 const paths=await page.evaluate(()=>(window as any).documentFixture.paths as string[]);
 await expect(dialog.locator('details').filter({hasText:'Harvest Moon'}).locator('.document-full-path')).toHaveText(paths[0]);
 await expect(dialog.getByRole('button',{name:'Close document Harvest Moon',exact:true})).toBeVisible();
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);
 await expect(tabs.getByRole('tab',{name:'Harvest Moon',exact:true})).toHaveAttribute('aria-selected','true');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 expect((await new AxeBuilder({page}).include('.document-workspace').analyze()).violations).toEqual([]);
 await first.focus();await page.locator('.document-tabs').scrollIntoViewIfNeeded();
 await page.screenshot({path:info.outputPath('readable-tabs-hc200.png')});
 expect(await page.evaluate(()=>JSON.stringify((window as any).documentFixture.fixture.documents))).toBe(initial);
 expect(await page.evaluate(()=>(window as any).documentFixture.fixture.externalCalls)).toEqual([]);
 expect(errors).toEqual([]);
});
