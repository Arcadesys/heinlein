test('Keyboard steps through every Reading suggestion and opens the one reached, with no extra tab stops in the prose', async ({ page }) => {
  await start(page);
  await openReading(page);
  await reader(page).focus();
  expect(await reader(page).locator('.markdown-reader-content span[tabindex], .markdown-reader-content em[tabindex]').count()).toBe(0);
  for (const id of ['example-frontmatter', 'example-insert', 'example-approve', 'example-heading-mark', 'example-overlap-phrase', 'example-overlap-word', 'example-dismiss']) {
    await reader(page).focus();
    await page.keyboard.press(`${modifier}+Alt+]`);
    await page.keyboard.press(`${modifier}+Alt+o`);
    const card = panelOf(page).locator(`[data-finding-id="${id}"]`);
    if (id.startsWith('example-overlap')) await expect(panelOf(page).locator('.review-conflict')).toBeFocused();
    else await expect(card.locator('h4')).toBeFocused();
    await panelOf(page).getByRole('button', { name: 'Return to writing', exact: true }).click();
  }
  expect(await decisionCalls(page)).toEqual([]);
});
test('Selecting in Reading cannot ask, split, undo or find through the hidden editor', async ({ page }) => {
  await start(page);
  await openReading(page);
  const panel = panelOf(page);
  const paragraph = reader(page).locator('p', { hasText: 'Marlo counted' });
  await paragraph.evaluate(n => n.scrollIntoView({ block: 'start' }));
  const whole = (await paragraph.boundingBox())!;
  const box = { x: whole.x, y: whole.y, width: whole.width, height: Math.min(whole.height, 120) };
  await page.mouse.move(box.x + 4, box.y + 10);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width - 8, box.y + box.height - 10, { steps: 6 });
  await page.mouse.up();
  expect(await page.evaluate(() => getSelection()!.toString().length)).toBeGreaterThan(0);
  await expect(panel).toBeHidden();
  for (const name of ['Ask about selection', 'Ask Heinlein about selection', 'Split scene at cursor', 'Undo', 'Redo', 'Find']) await expect(page.getByRole('button', { name, exact: true })).toBeHidden();
  const before = await source(page);
  const status = page.locator('.status');
  await page.keyboard.press(`${modifier}+j`);
  await expect(status).toContainText('Switch to Source');
  await page.keyboard.press(`${modifier}+Shift+P`);
  await page.keyboard.type('Find in scene');
  await page.keyboard.press('Enter');
  await expect(status).toContainText('Switch to Source');
  await expect(page.locator('.cm-panels')).toHaveCount(0);
  await page.keyboard.press(`${modifier}+Shift+P`);
  await page.keyboard.type('Split scene');
  await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(status).toContainText('Switch to Source');
  expect(await source(page)).toBe(before);
  await expect(page.getByRole('button', { name: 'Heinlein Review', exact: true })).toBeVisible();
});
test('Toggling keeps one writer: unsaved text shows in Reading, caret and bytes survive, and marks stop after an edit', async ({ page }) => {
  await start(page);
  await panelOf(page).getByRole('button', { name: 'Return to writing', exact: true }).click();
  const group = page.getByRole('group', { name: 'Document view' });
  const editor = page.locator('.cm-content');
  await editor.click();
  await page.keyboard.press(`${modifier}+ArrowDown`);
  await page.keyboard.type('Unsaved 🦊 line.');
  await group.getByRole('button', { name: 'Reading', exact: true }).click();
  await expect(reader(page)).toContainText('Unsaved 🦊 line.');
  await expect(reader(page).locator('[data-review-id]')).toHaveCount(0);
  await expect(page.locator('.cm-editor')).toBeHidden();
  await group.getByRole('button', { name: 'Source', exact: true }).click();
  await expect(reader(page)).toBeHidden();
  await expect(page.locator('.cm-editor')).toBeVisible();
  await editor.click();
  await page.keyboard.press(`${modifier}+ArrowDown`);
  await page.keyboard.type(' More.');
  await page.keyboard.press(`${modifier}+s`);
  await expect.poll(() => source(page)).toContain('Unsaved 🦊 line. More.');
  const saved = await source(page);
  const original = await baseline(page);
  expect(saved.startsWith(original)).toBe(true);
  expect(saved.slice(0, original.length)).toContain('---\r\ntitle: "The Salt Ledger — invented"\r\n---\r\n');
});
