import { test, expect, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
// Invented text and a simulated backend, through the production panel, reader and writer.
const url = '/tests/browser/markdown-reading.html';
const modifier = process.platform === 'darwin' ? 'Meta' : 'Control';
const panelOf = (page: Page) => page.getByRole('region', { name: 'Heinlein Review', exact: true });
// By class, not role: an open review panel is a full sheet on narrow windows, which hides the page beneath it.
const reader = (page: Page) => page.locator('.active-document-pane .markdown-reader');
const source = (page: Page, path = 'opening.md') => page.evaluate(p => (window as any).readingFixture.docs[p] as string, path);
const baseline = (page: Page, path = 'opening.md') => page.evaluate(p => (window as any).readingFixture.baseline[p] as string, path);
const decisionCalls = (page: Page) => page.evaluate(() => (window as any).readingFixture.calls.filter((c: any) => c.action !== 'preview'));
async function start(page: Page, path = url) {
  await page.goto(path);
  await page.evaluate(() => localStorage.clear());
  await page.goto(path);
  await expect(panelOf(page).locator('.review-edit').first()).toBeVisible();
  await expect(panelOf(page).locator('.review-mark-status')).toContainText('marked in the open text');
}
async function openReading(page: Page) {
  await panelOf(page).getByRole('button', { name: 'Return to writing', exact: true }).click();
  await page.getByRole('group', { name: 'Document view' }).getByRole('button', { name: 'Reading', exact: true }).click();
  await expect(reader(page)).toBeVisible();
}
const mark = (page: Page, id: string) => reader(page).locator(`[data-review-id="${id}"]`);

test('Reading is explicit, formats safely, makes no requests and leaves source bytes alone', async ({ page }) => {
  const external: string[] = [];
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1')) external.push(request.url()); });
  await start(page);
  await panelOf(page).getByRole('button', { name: 'Return to writing', exact: true }).click();
  const group = page.getByRole('group', { name: 'Document view' });
  await expect(group.getByRole('button', { name: 'Source', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(reader(page)).toBeHidden();
  const before = await source(page);
  await group.getByRole('button', { name: 'Reading', exact: true }).click();
  await expect(reader(page)).toBeVisible();
  await expect(group.getByRole('button', { name: 'Reading', exact: true })).toHaveAttribute('aria-pressed', 'true');
  // Entering Reading keeps the focused toggle in view. The Studio root may only move where it is the real scroller, as on narrow windows.
  await expect(group.getByRole('button', { name: 'Reading', exact: true })).toBeInViewport({ ratio: 1 });
  expect(await page.evaluate(() => { const studio = document.querySelector('.studio')!; return [getComputedStyle(studio).overflowY === 'hidden' ? studio.scrollTop : 0, document.documentElement.scrollTop, document.body.scrollTop]; })).toEqual([0, 0, 0]);
  const view = reader(page);
  await expect(view.locator('h3')).toHaveText('The Salt Ledger');
  await expect(view.locator('h4')).toContainText('Inventory');
  await expect(view.locator('em').first()).toHaveText('very');
  await expect(view.locator('strong')).toHaveText('crates');
  await expect(view.locator('ul li')).toHaveCount(2);
  await expect(view.locator('ol li')).toHaveCount(2);
  await expect(view.locator('blockquote')).toContainText('Nobody signs twice.');
  await expect(view.locator('th').first()).toHaveText('Crate');
  await expect(view.locator('pre.md-code')).toContainText('alert("never runs");');
  await expect(view.locator('.md-link').first()).toHaveText('harbor map (https://example.test/map)');
  await expect(view.locator('.md-link-blocked')).toContainText('blocked link: javascript:alert(1)');
  await expect(view.locator('.md-image')).toHaveText('Image not loaded: Harbor at dusk (https://example.test/harbor.png)');
  await expect(view).toContainText('<img src="https://example.test/tracker.png" onerror="alert(1)">');
  await expect(view).toContainText('Rope &amp; tar');
  await expect(view).toContainText('🐺');
  await expect(view).toContainText('late — it always did.');
  await expect(view).not.toContainText('title: "The Salt');
  await expect(view).toContainText('Frontmatter is not shown');
  expect(await view.locator('img,a,script,iframe,svg,object,embed,video,audio').count()).toBe(0);
  await view.locator('.md-link').first().click();
  await view.locator('.md-link-blocked').click();
  await page.waitForTimeout(150);
  expect(page.url()).toContain(url);
  expect(external).toEqual([]);
  expect(await source(page)).toBe(before);
  expect((await new AxeBuilder({ page }).include('.markdown-reader').include('.md-view-toggle').analyze()).violations).toEqual([]);
});
