import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const activate = async (l: import('@playwright/test').Locator) => { await l.focus(); await l.page().keyboard.press('Enter'); };
const writing = (p: import('@playwright/test').Page) => p.locator('.standalone-editor .cm-content');
test('start without setup, local keep/restart/find/resume/discard/restore by keyboard', async ({ page }) => {
    await page.goto('/tests/browser/standalone.html');
    await expect(writing(page)).toBeVisible();
    await expect(writing(page)).toBeFocused();
    expect(await page.evaluate(() => (window as any).draftFixture.calls.map((c: any) => c.kind))).toEqual(['list']);
    await page.keyboard.insertText('First — 🐺 e\u0301 story.');
    await activate(page.getByRole('button', { name: 'Keep on this Mac', exact: true }));
    await expect(page.locator('.standalone-page [role=status]')).toHaveText('Kept on this Mac');
    await page.reload();
    await expect(writing(page)).toContainText('First — 🐺 e\u0301 story.');
    await activate(page.getByRole('button', { name: 'New draft', exact: true }).first());
    await expect(writing(page)).toHaveText('');
    await page.keyboard.insertText('Second independent draft');
    await activate(page.getByRole('button', { name: 'Keep on this Mac', exact: true }));
    await activate(page.getByRole('button', { name: 'Drafts', exact: true }).first());
    const list = page.getByRole('dialog', { name: 'Drafts on this Mac' });
    await expect(list).toContainText('First —');
    await activate(list.getByRole('button', { name: /First —/ }));
    await expect(writing(page)).toContainText('First —');
    await activate(page.getByText('Draft actions', { exact: true }));
    page.once('dialog', d => d.dismiss());
    await activate(page.getByRole('button', { name: 'Remove draft…' }));
    await expect(writing(page)).toContainText('First —');
    page.once('dialog', d => d.accept());
    await activate(page.getByRole('button', { name: 'Remove draft…' }));
    await expect(writing(page)).toHaveText('');
    await page.reload();
    await activate(page.getByRole('button', { name: 'Drafts', exact: true }).first());
    await expect(list).toContainText('Discarded drafts');
    await activate(list.getByRole('button', { name: /First —/ }));
    await activate(page.getByRole('button', { name: 'Restore draft', exact: true }));
    await expect(writing(page)).toContainText('First —');
    await expect(writing(page)).toHaveAttribute('contenteditable', 'true');
    expect(await page.evaluate(() => (window as any).draftFixture.calls.every((c: any) => ['list', 'open', 'release', 'restore'].includes(c.kind)))).toBe(true);
});
test('200 percent narrow writing, labelled placement, exact preview/cancel/copy and accessible focus', async ({ page }) => {
    await page.goto('/tests/browser/standalone.html');
    await expect(writing(page)).toBeFocused();
    await activate(page.getByRole('button',{name:/^Appearance/}));
    await activate(page.getByRole('button',{name:'High contrast',exact:true}));
    await page.keyboard.press('Escape');
    await writing(page).focus();
    await expect(page.locator('html')).toHaveAttribute('data-theme','contrast');
    for (let i = 0; i < 5; i++)
        await page.keyboard.press(process.platform === 'darwin' ? 'Meta+=' : 'Control+=');
    await expect(page.locator('html')).toHaveAttribute('data-zoom', '200');
    await page.keyboard.insertText('Exact — text 🐺');
    await activate(page.getByRole('button', { name: 'Keep on this Mac', exact: true }));
    const area = page.locator('.standalone-page');
    expect(await area.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
    if (test.info().project.name === 'narrow')
        await page.screenshot({ path: '/tmp/heinlein-standalone-320-200.png', fullPage: true });
    const keep=page.getByRole('button',{name:'Keep on this Mac',exact:true});
    await keep.focus();
    expect(await keep.evaluate(e=>{const r=e.getBoundingClientRect();return document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)?.closest('button')===e;})).toBe(true);
    const editorBox = await writing(page).boundingBox();
    expect(editorBox!.height).toBeGreaterThan(100);
    for (const b of await page.locator('.standalone-toolbar > button').all()) {
        expect((await b.boundingBox())!.height).toBeGreaterThanOrEqual(44);
    }
    expect((await new AxeBuilder({ page }).include('.standalone-page').analyze()).violations).toEqual([]);
    await activate(page.getByRole('button', { name: 'Choose a destination…' }));
    const d = page.getByRole('dialog', { name: 'Choose a destination', exact: true });
    await expect(d).toContainText('independent copy');
    await d.getByLabel('Destination type').selectOption('existingProject');
    await activate(d.getByRole('button', { name: 'Choose location and preview…' }));
    await expect(d.locator('pre')).toHaveText('Exact — text 🐺');
    expect(await d.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
    expect((await new AxeBuilder({ page }).include('.standalone-dialog').analyze()).violations).toEqual([]);
    await activate(d.getByRole('button', { name: 'Cancel', exact: true }));
    await expect(writing(page)).toBeFocused();
    await expect(writing(page)).toHaveText('Exact — text 🐺');
    await activate(page.getByRole('button', { name: 'Choose a destination…' }));
    await activate(d.getByRole('button', { name: 'Choose location and preview…' }));
    page.once('dialog', dialog => dialog.accept());
    await activate(d.getByRole('button', { name: 'Place copy…' }));
    await expect(d).toContainText('Your original stays here');
    await activate(d.getByRole('button', { name: 'Keep editing original' }));
    await expect(writing(page)).toBeFocused();
    await page.keyboard.insertText(' newer');
    await activate(page.getByRole('button', { name: 'Keep on this Mac', exact: true }));
    await expect(writing(page)).toContainText('newer');
    expect(await page.evaluate(() => (window as any).draftFixture.externalCalls)).toEqual([]);
    const saved = await page.evaluate(() => [...(window as any).draftFixture.records.values()][0]);
    expect(saved.placements).toHaveLength(1);
    expect(saved.text).toContain('newer');
    expect(saved.placements[0].sourceRevision).toBeLessThan(saved.revision);
});
test('failed keep blocks normal close and explicit retry succeeds without losing writing', async ({ page }) => {
    await page.goto('/tests/browser/standalone.html');
    await expect(writing(page)).toBeFocused();
    await page.keyboard.insertText('Unsaved — buffer');
    await page.evaluate(() => (window as any).draftFixture.failNextSave());
    await page.evaluate(() => (window as any).draftFixture.close());
    await expect(page.locator('.standalone-page [role=status]')).toContainText('Not kept yet');
    expect(await page.evaluate(() => (window as any).draftFixture.dirty)).toBe(true);
    await expect(writing(page)).toHaveText('Unsaved — buffer');
    await activate(page.getByRole('button', { name: 'Retry keeping on this Mac' }));
    await expect(page.locator('.standalone-page [role=status]')).toHaveText('Kept on this Mac');
    expect(await page.evaluate(() => (window as any).draftFixture.dirty)).toBe(false);
});
