import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('unified revisions show exact diffs without reflow and keep both origins in one history', async({page},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/tests/browser/revisions.html');
  await expect(page).toHaveTitle('Synthetic unified revisions');
  const editor=page.locator('.cm-editor');await expect(editor).toBeVisible();
  const before=await editor.boundingBox();
  const sourceBefore=await page.evaluate(()=>(window as any).revisionsFixture.text);
  const entry=page.getByRole('button',{name:'Revisions',exact:true});
  await expect(entry).toBeVisible();await expect(entry.locator('..')).toHaveClass(/status-pill/);
  await entry.click();
  const dialog=page.getByRole('dialog',{name:'Revisions',exact:true});await expect(dialog).toBeVisible();
  await expect(dialog.locator('.revision-entry')).toHaveCount(3);
  await expect(dialog.getByRole('heading',{name:'Before',exact:true})).toHaveCount(3);
  await expect(dialog.getByRole('heading',{name:'After',exact:true})).toHaveCount(3);
  const removed=dialog.locator('del.question-diff-remove').first(),added=dialog.locator('ins.question-diff-add').first();
  expect(await removed.evaluate(e=>getComputedStyle(e).textDecorationLine)).toContain('line-through');
  expect(await added.evaluate(e=>getComputedStyle(e).textDecorationLine)).toContain('underline');
  expect(await removed.evaluate(e=>getComputedStyle(e).backgroundColor)).not.toBe(await added.evaluate(e=>getComputedStyle(e).backgroundColor));
  expect(await editor.boundingBox()).toEqual(before);
  expect(await page.evaluate(()=>(window as any).revisionsFixture.text)).toBe(sourceBefore);
  expect(await page.evaluate(()=>(window as any).revisionsFixture.calls)).toEqual([]);
  expect(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
  expect((await new AxeBuilder({page}).include('.revisions-dialog').analyze()).violations).toEqual([]);
  await page.screenshot({path:`/tmp/heinlein-revisions-${testInfo.project.name}.png`});
  await dialog.getByRole('button',{name:'Pending',exact:true}).click();
  await expect(dialog.locator('.revision-entry')).toHaveCount(2);
  const inApp=dialog.locator('.revision-entry').filter({hasText:'In-app review'});
  await inApp.getByRole('button',{name:'Keep mine',exact:true}).click();await expect(dialog.locator('.revision-entry')).toHaveCount(1);
  await dialog.getByRole('button',{name:'History',exact:true}).click();await expect(dialog.locator('.revision-entry')).toHaveCount(2);
  await expect(dialog.locator('del.question-diff-remove').filter({hasText:'waited'})).toBeVisible();
  await dialog.getByRole('button',{name:'Pending',exact:true}).click();await dialog.getByRole('button',{name:'Accept',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>(window as any).revisionsFixture.text)).toBe(sourceBefore.replace('tapped','drummed'));
  await expect(page.getByRole('dialog',{name:'Review whole-scene proposal',exact:true})).not.toBeVisible();
  await expect(dialog).toBeVisible();
await dialog.getByRole('button',{name:'All revisions',exact:true}).click();
  await expect(dialog.locator('.revision-entry')).toHaveCount(3);await expect(dialog.locator('[data-status="applied"]')).toHaveCount(2);
  await expect(dialog.locator('[data-status="kept"]')).toHaveCount(1);
  expect(errors).toEqual([]);
});
